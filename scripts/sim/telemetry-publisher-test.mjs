import assert from 'node:assert/strict';
import {createTelemetryPublisher} from '../../apps/web/src/phone/telemetry.ts';
let next=0;const frames=new Map(),cancelled=[];
const clock={request(callback){const id=next++;frames.set(id,callback);return id;},cancel(id){cancelled.push(id);frames.delete(id);}};
const published=[];
const initial={rtt:'-',rttAvg:'-',sent:0,unacked:0,path:'-',advice:'',inputMetrics:'',burstBusy:false};
const publisher=createTelemetryPublisher(initial,value=>published.push(value),clock);
publisher.patch({sent:1,unacked:1});publisher.patch({unacked:0,rtt:'5ms'});
assert.equal(published.length,0,'ACK callback中に購読先を呼ばない');assert.equal(frames.size,1,'同一frameの通知は一つ');
const first=frames.get(0);frames.delete(0);first();
assert.equal(published.length,1);assert.equal(published[0].sent,1);assert.equal(published[0].unacked,0);assert.equal(published[0].rtt,'5ms');
assert.equal(initial.sent,0,'既存snapshotを変更しない');
publisher.patch({sent:2});const stale=frames.get(1);publisher.dispose();publisher.dispose();
assert.deepEqual(cancelled,[1]);assert.equal(frames.size,0);stale();publisher.patch({sent:3});
assert.equal(published.length,1,'破棄後の古いframe/通知は無視');assert.equal(published[0].sent,1,'発行済みsnapshotも不変');
const another=createTelemetryPublisher(initial,value=>published.push(value),clock);
another.patch({path:'WSのみ'});const callback=[...frames.values()][0];frames.clear();callback();
assert.equal(published[1].path,'WSのみ','新しい寿命で更新を再開できる');another.dispose();
console.log('合格: 診断を入力/ACKから次frameへ分離、複数patch統合、snapshot不変、破棄後通知/古いframeの停止');
